// TC-12-05: the committed pgTAP parity file is the generator's output for the shared vectors.
import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import '../../tool/gen_recurring_sql.dart';

String _read(String path) => File(path).readAsStringSync().replaceAll('\r\n', '\n');

void main() {
  // TC-12-05
  test('supabase/tests/150_recurring_vectors.test.sql is up to date with the vectors', () {
    expect(
      _read(output),
      recurringSql(_read(fixture)),
      reason: 'run: dart run tool/gen_recurring_sql.dart',
    );
  });

  // TC-12-05
  test('plan(N) is the number of vectors and every vector has one assertion', () {
    final doc = jsonDecode(_read(fixture)) as Map<String, dynamic>;
    final vectors = (doc['vectors'] as List).cast<Map<String, dynamic>>();
    final sql = _read(output);
    expect(vectors, isNotEmpty);
    expect(sql, contains('select plan(${vectors.length});'));
    expect(
      RegExp(r'^select is\(pg_temp\.rec\(', multiLine: true).allMatches(sql),
      hasLength(vectors.length),
    );
    for (final v in vectors) {
      expect(sql, contains(", '${v['id']}');"), reason: 'vector ${v['id']}');
    }
  });

  // TC-12-05
  test('the generator output has the pgTAP frame', () {
    final sql = recurringSql(
      jsonEncode({
        'vectors': [
          {
            'id': "it's",
            'op': 'next',
            'input': {'interval': 'weekly', 'anchor': '2026-01-01', 'after': '2026-01-01'},
            'expect': {'next': '2026-01-08'},
          },
        ],
      }),
    );
    expect(sql, startsWith('-- GENERATED by tool/gen_recurring_sql.dart'));
    expect(sql, contains('begin;\nselect plan(1);'));
    expect(sql, contains("'it''s');"));
    expect(sql, contains("pg_temp.rec('next', \$j\$"));
    expect(sql.trimRight(), endsWith('select * from finish();\nrollback;'));
  });
}
