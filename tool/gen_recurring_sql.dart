// Generates the pgTAP parity test of the recurring next-date rules (phase 16, TC-12-05) from the vectors the
// Dart rules are tested with (test/fixtures/recurring_vectors.json):
//   supabase/tests/150_recurring_vectors.test.sql   every vector through the private.recurring_* functions
// Run: dart run tool/gen_recurring_sql.dart   (test/tool/gen_recurring_sql_test.dart fails when it is stale)
// ignore_for_file: avoid_print
import 'dart:convert';
import 'dart:io';

const fixture = 'test/fixtures/recurring_vectors.json';
const output = 'supabase/tests/150_recurring_vectors.test.sql';

void main() {
  File(output).writeAsStringSync(recurringSql(File(fixture).readAsStringSync()));
  print('Generated $output from $fixture.');
}

/// The test file for the vectors document [json].
String recurringSql(String json) {
  final doc = jsonDecode(json) as Map<String, dynamic>;
  final vectors = (doc['vectors'] as List).cast<Map<String, dynamic>>();
  final b = StringBuffer()
    ..writeln('-- GENERATED by tool/gen_recurring_sql.dart from $fixture. Do not edit by hand.')
    ..writeln('-- Regenerate: dart run tool/gen_recurring_sql.dart')
    ..writeln(
      '-- TC-12-05: the SQL next-date rules (0019) give the same dates as lib/domain/rules/recurrence.dart.',
    )
    ..writeln('begin;')
    ..writeln('select plan(${vectors.length});')
    ..writeln(_runner);
  for (final v in vectors) {
    b.writeln(
      'select is(pg_temp.rec(${_lit(v['op'] as String)}, ${_json(v['input'])}), '
      '${_json(v['expect'])}, ${_lit(v['id'] as String)});',
    );
  }
  b
    ..writeln('select * from finish();')
    ..writeln('rollback;');
  return b.toString();
}

String _lit(String s) => "'${s.replaceAll("'", "''")}'";

String _json(Object? value) => '\$j\$${jsonEncode(value)}\$j\$::jsonb';

// Same order of checks as Recurrence.parse: interval, anchor, end date, end before anchor, then the op.
const _runner = r'''
create function pg_temp.rec(p_op text, i jsonb) returns jsonb language plpgsql as $f$
declare
  r record;
  a date;
  e date;
  msg text;
begin
  perform private.recurring_check(i ->> 'interval', date '2000-01-01', null);
  a := private.recurring_date(i ->> 'anchor');
  e := private.recurring_date(i ->> 'ends_on');
  perform private.recurring_check(i ->> 'interval', a, e);
  if p_op = 'next' then
    return jsonb_build_object('next', to_char(private.recurring_next_after(i ->> 'interval', a, e,
      private.recurring_date(i ->> 'after')), 'YYYY-MM-DD'));
  elsif p_op = 'series' then
    return jsonb_build_object('dates', (
      select coalesce(jsonb_agg(to_char(private.recurring_occurrence(i ->> 'interval', a, n), 'YYYY-MM-DD')
                                order by n), '[]'::jsonb)
      from generate_series(0, (i ->> 'count')::int - 1) n));
  end if;
  select * into r from private.recurring_run(i ->> 'interval', a, e, private.recurring_date(i ->> 'next_date'),
                                             private.recurring_date(i ->> 'today'));
  return jsonb_build_object(
    'dates', (select coalesce(jsonb_agg(to_char(x, 'YYYY-MM-DD') order by o), '[]'::jsonb)
              from unnest(r.dates) with ordinality u(x, o)),
    'next', to_char(r.next_copy, 'YYYY-MM-DD'));
exception when sqlstate 'P0001' then
  get stacked diagnostics msg = message_text;
  return jsonb_build_object('error', msg);
end;
$f$;''';
