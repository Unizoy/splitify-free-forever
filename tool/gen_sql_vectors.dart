// Generates the pgTAP money-parity tests from the shared money vectors (planning/09-testing-strategy.md §2):
//   supabase/tests/010_money_vectors.test.sql  every vector through the money.* functions
//   supabase/tests/030_balances.test.sql       BAL-* vectors through public.group_balances on real rows,
//                                              plus per-currency / converted / my_overview checks
// Run: dart run tool/gen_sql_vectors.dart   (CI fails when the committed files are stale)
// ignore_for_file: avoid_print
import 'dart:convert';
import 'dart:io';

const _fixture = 'test/fixtures/money_vectors.json';
const _oracle = 'planning/reference/money_vectors.json';

void main() {
  final source = File(_fixture).existsSync() ? _fixture : _oracle;
  final doc = jsonDecode(File(source).readAsStringSync()) as Map<String, dynamic>;
  final vectors = (doc['vectors'] as List).cast<Map<String, dynamic>>();

  _write('supabase/tests/010_money_vectors.test.sql', _moneyVectors(vectors, source));
  _write('supabase/tests/030_balances.test.sql', _balances(vectors, source));
  print('Generated SQL tests from $source (${vectors.length} vectors).');
}

void _write(String path, String content) => File(path).writeAsStringSync(content);

String _lit(String s) => "'${s.replaceAll("'", "''")}'";

String _textArray(List<dynamic> items) => items.isEmpty
    ? 'array[]::text[]'
    : 'array[${items.map((e) => _lit(e as String)).join(', ')}]::text[]';

String _json(Object? value) => '\$j\$${jsonEncode(value)}\$j\$::jsonb';

String _header(String source) =>
    '-- GENERATED by tool/gen_sql_vectors.dart from $source. Do not edit by hand.\n'
    '-- Regenerate: dart run tool/gen_sql_vectors.dart\n';

/// SQL expression returning the vector's result as jsonb (wrapped by pg_temp.run).
String _query(Map<String, dynamic> v) {
  final i = v['input'] as Map<String, dynamic>;
  switch (v['op']) {
    case 'split':
      return 'select money.split(${i['total']}, ${_lit(i['kind'] as String)}, '
          '${_textArray(i['members'] as List)}, ${_json(i['values'])})';
    case 'check_payers':
      return 'select to_jsonb(money.check_payers(${i['total']}, ${_json(i['paid'])}))';
    case 'balances':
      final o = _textArray(i['order'] as List);
      final e = _json(i['expenses']);
      final p = _json(i['payments']);
      return "select jsonb_build_object('nets', money.nets($o, $e, $p), "
          "'pairs', money.pairwise($o, $e, $p), "
          "'simplified', money.simplify($o, money.nets($o, $e, $p)))";
    case 'convert':
      return 'select to_jsonb(money.convert(${i['amount']}, ${_lit(i['from'] as String)}, '
          '${_lit(i['to'] as String)}, ${_lit(i['rate'] as String)}::numeric))';
    case 'convert_expense':
      return 'select money.convert_expense(${i['total']}, ${_lit(i['from'] as String)}, '
          '${_lit(i['to'] as String)}, ${_lit(i['rate'] as String)}::numeric, '
          '${_textArray(i['order'] as List)}, ${_json(i['paid'])}, ${_json(i['shares'])})';
    case 'cross_rate':
      return 'select to_jsonb(money.cross_rate(${_json(i['eur_rates'])}, '
          '${_lit(i['from'] as String)}, ${_lit(i['to'] as String)})::text)';
  }
  throw StateError('Unknown op ${v['op']} in ${v['id']}');
}

const _runHelper = r'''
-- Runs a query and returns the oracle's result envelope: {"ok": result} or {"error": CODE, "data": {...}}.
create function pg_temp.run(q text) returns jsonb language plpgsql as $f$
declare
  r jsonb;
  msg text;
  det text;
begin
  execute q into r;
  return jsonb_build_object('ok', r);
exception when sqlstate 'P0001' then
  get stacked diagnostics msg = message_text, det = pg_exception_detail;
  return jsonb_build_object('error', msg)
    || case when coalesce(det, '') = '' then '{}'::jsonb else jsonb_build_object('data', det::jsonb) end;
end;
$f$;
''';

String _moneyVectors(List<Map<String, dynamic>> vectors, String source) {
  final b = StringBuffer()
    ..write(_header(source))
    ..writeln(
      '-- TC-5..9-05 (split parity), TC-15-02, TC-17-02, TC-32-03: SQL money engine = oracle.',
    )
    ..writeln('begin;')
    ..writeln('select plan(${vectors.length});')
    ..write(_runHelper);
  for (final v in vectors) {
    b.writeln(
      'select is(pg_temp.run(\$q\$${_query(v)}\$q\$), ${_json(v['expected'])}, ${_lit(v['id'] as String)});',
    );
  }
  b
    ..writeln('select * from finish();')
    ..writeln('rollback;');
  return b.toString();
}

String _id(int prefix, int n) => '${prefix}0000000-0000-4000-8000-${n.toString().padLeft(12, '0')}';

const _userA = '00000000-0000-4000-8000-0000000000a1';

String _balances(List<Map<String, dynamic>> vectors, String source) {
  final bal = vectors.where((v) => v['op'] == 'balances').toList();
  final b = StringBuffer()
    ..write(_header(source))
    ..writeln(
      '-- TC-15-02, TC-17-02 via group_balances on real rows; TC-14-03 per-currency blocks; TC-16-02.',
    )
    ..writeln('begin;')
    ..writeln('select plan(${bal.length + _staticAssertions});')
    ..writeln()
    ..writeln('insert into auth.users (id, email) values')
    ..writeln("  ('$_userA', 'bal-a@splitify.test'),")
    ..writeln("  ('00000000-0000-4000-8000-0000000000b1', 'bal-b@splitify.test'),")
    ..writeln("  ('00000000-0000-4000-8000-0000000000c1', 'bal-c@splitify.test');")
    ..writeln();
  final asserts = StringBuffer();
  for (var k = 0; k < bal.length; k++) {
    final v = bal[k];
    final input = v['input'] as Map<String, dynamic>;
    final order = (input['order'] as List).cast<String>();
    final g = _id(1, k + 1);
    final member = {for (var i = 0; i < order.length; i++) order[i]: _id(2, (k + 1) * 100 + i)};
    Map<String, dynamic> remap(Map<String, dynamic> m) => {
      for (final e in m.entries) member[e.key]!: e.value,
    };
    b
      ..writeln('-- ${v['id']}')
      ..writeln("insert into public.groups (id, name) values ('$g', ${_lit('${v['id']}')});")
      ..writeln(
        'insert into public.group_members (id, group_id, user_id, display_name, position) values',
      );
    for (var i = 0; i < order.length; i++) {
      final user = i == 0 ? "'$_userA'" : 'null';
      final sep = i == order.length - 1 ? ';' : ',';
      b.writeln("  ('${member[order[i]]}', '$g', $user, ${_lit(order[i])}, $i)$sep");
    }
    final exps = (input['expenses'] as List).cast<Map<String, dynamic>>();
    for (var j = 0; j < exps.length; j++) {
      final paid = remap(exps[j]['paid'] as Map<String, dynamic>);
      final shares = remap(exps[j]['shares'] as Map<String, dynamic>);
      final total = paid.values.fold<int>(0, (a, x) => a + (x as int));
      b.writeln(
        'insert into public.expenses (id, group_id, description, date, currency, total, payers, shares, '
        "split_kind) values ('${_id(3, (k + 1) * 100 + j)}', '$g', 'Expense ${j + 1}', '2026-11-01', 'INR', "
        "$total, ${_json(paid)}, ${_json(shares)}, 'exact');",
      );
    }
    final pays = (input['payments'] as List).cast<Map<String, dynamic>>();
    for (var j = 0; j < pays.length; j++) {
      b.writeln(
        'insert into public.payments (id, group_id, from_member, to_member, amount, currency, date) values '
        "('${_id(4, (k + 1) * 100 + j)}', '$g', '${member[pays[j]['from']]}', '${member[pays[j]['to']]}', "
        "${pays[j]['amount']}, 'INR', '2026-11-02');",
      );
    }
    final ok = (v['expected'] as Map<String, dynamic>)['ok'] as Map<String, dynamic>;
    List<List<Object?>> remapTransfers(List<dynamic> t) => [
      for (final x in t.cast<List<dynamic>>()) [member[x[0]], member[x[1]], x[2]],
    ];
    final expected = {
      'nets': remap(ok['nets'] as Map<String, dynamic>),
      'pairs': remapTransfers(ok['pairs'] as List),
      'simplified': remapTransfers(ok['simplified'] as List),
    };
    asserts.writeln(
      "select is(public.group_balances('$g') -> 'currencies' -> 'INR', ${_json(expected)}, "
      "${_lit('${v['id']} via group_balances')});",
    );
  }
  b
    ..writeln()
    ..writeln('set local role authenticated;')
    ..writeln('set local request.jwt.claims = \'{"sub":"$_userA","role":"authenticated"}\';')
    ..write(asserts)
    ..write(_staticPart);
  return b.toString();
}

